    def _resample_is_differentiated(self) -> bool:
        """Whether a resample issued right now should record a graph.

        Mirrors ``Simulation._solve_is_differentiated``. Rendering and
        ``collect_statistics`` run under ``no_grad``, so they keep the compiled
        kernel and pay nothing for this.
        """
        return self._differentiable and torch.is_grad_enabled()

    def _diff_resampler(self, out_indices: torch.Tensor | None = None):
        """Cached differentiable resampler, optionally restricted to some cells.

        The compiled kernel has no autograd support, so everything downstream of
        it is detached; this is the pure-torch equivalent, which is not.

        The resample is a fixed linear map (all the masks are geometry), so the
        operator is built once, and ``out_indices`` keeps only the rows for the
        cells actually read. That restriction is exact. It also matters: a few hundred
        sensors need only a small fraction of the operator and tape of the full
        grid.
        """
        from phipict.grid.resample import DiffMultiblockResampler

        coords = self._sim.output_resampling_coords
        out_shape = self._sim.output_resampling_shape
        fill_max_steps = self._sim.output_resampling_fill_max_steps
        dtype = self._domain.getBlocks()[0].velocity.dtype

        # `output_resampling_coords` falls through to `domain.getVertexCoordinates()`,
        # which hands back a fresh list of fresh tensor objects on every call, so
        # `id()` is no identity for the grid: the lookup missed every time and the
        # operator was rebuilt once per differentiated observation. A full weight
        # assembly inside every replayed backward step. The key below is the geometry
        # itself, and the entry holds the tensors it was built from, so the storage
        # behind an address cannot be freed and reallocated while an entry names it
        # (which is the way a `data_ptr` key goes stale and silently serves the wrong
        # operator)
        grid_key = (
            None
            if coords is None
            else tuple((t.data_ptr(), tuple(t.shape), t.dtype) for t in coords)
        )
        out_key = (
            None
            if out_indices is None
            else (out_indices.data_ptr(), tuple(out_indices.shape), out_indices.dtype)
        )
        shape_key = None if out_shape is None else tuple(out_shape)
        key = (grid_key, out_key, shape_key, fill_max_steps, dtype)

        cached = self.__diff_resamplers.get(key)
        if cached is not None:
            return cached[1]

        resampler = DiffMultiblockResampler(
            coords_list=coords,
            out_shape=out_shape,
            dtype=dtype,
            fill_max_steps=fill_max_steps,
            out_indices=out_indices,
        )
        # Keep only the operators for the current grid, so `set_state` cannot
        # accumulate one hierarchy per rebuild. This also releases the previous
        # grid's coordinates, which the dropped entries were keeping alive
        self.__diff_resamplers = {
            k: v for k, v in self.__diff_resamplers.items() if k[0] == grid_key
        }
        keep_alive = (
            list(coords or ())
            if out_indices is None
            else [*(coords or ()), out_indices]
        )
        self.__diff_resamplers[key] = (keep_alive, resampler)
        return resampler

    def _fold_envs(
        self, data_list: list[torch.Tensor]
    ) -> tuple[list[torch.Tensor], int]:
        """Fold the env dim of per-block data into the channels, for the samplers.

        The samplers resample ``[1, C, ...]`` data with any number of channels, so
        ``[E, C, ...]`` is resampled as ``[1, E * C, ...]`` in one call. Data shared
        by all environments (``[1, C, ...]``) is broadcast first.
        """
        n_envs = max(data.size(0) for data in data_list)
        if n_envs == 1:
            return data_list, 1
        folded = []
        for data in data_list:
            if data.size(0) != n_envs:
                data = data.expand(n_envs, *data.shape[1:])
            folded.append(data.reshape(1, -1, *data.shape[2:]))
        return folded, n_envs

    def _resample_blocks(self, data_list: list[torch.Tensor]) -> torch.Tensor:
        """Resample per-block cell data onto the uniform output grid.

        This is the sampler behind :meth:`get_velocity`, :meth:`get_pressure` and
        :meth:`get_vorticity`, and hence behind the observations. For rendering,
        prefer :meth:`_render_plane`, which interpolates and is free of the block
        artifacts of this sampler.

        On a differentiable environment with grad enabled this routes to the
        pure-torch resampler, so the observation stays connected to the action;
        otherwise it uses the compiled kernel, which detaches.

        Parameters
        ----------
        data_list: list[torch.Tensor]
            Per-block cell data, one entry per block of the domain.

        Returns
        -------
        torch.Tensor
            The resampled data of shape [E, C, Y, X] for 2D or [E, C, Z, Y, X] for
            3D, with E the number of environments.
        """
        folded, n_envs = self._fold_envs(data_list)
        if self._resample_is_differentiated():
            out = self._diff_resampler()(folded)
        else:
            assert self._sim.output_resampling_coords is not None
            assert self._sim.output_resampling_shape is not None

            out = _resample_block_data(
                data_list=folded,
                vertex_coord_list=self._sim.output_resampling_coords,
                resampling_out_shape=self._sim.output_resampling_shape,
                ndims=self._ndims,
                fill_max_steps=self._sim.output_resampling_fill_max_steps,
            )
        return out.reshape(n_envs, -1, *out.shape[2:])

    def _resample_blocks_at(
        self, data_list: list[torch.Tensor], out_indices: torch.Tensor
    ) -> torch.Tensor:
        """Resample per-block data straight to selected output cells.

        For point-sensor observations: same values as resampling the whole grid
        and indexing it, at ~1e-4 of the cost. ``out_indices`` is a flat index or
        a ``[dims, R]`` tensor of per-axis ``(x, y[, z])`` indices; results come
        back as ``[E, C, R]`` in the order given, with E the number of
        environments.
        """
        if self._resample_is_differentiated():
            folded, n_envs = self._fold_envs(data_list)
            out = self._diff_resampler(out_indices)(folded)
            return out.reshape(n_envs, -1, out.size(-1))

        full = self._resample_blocks(data_list)
        if out_indices.dim() == 2:
            idx = [out_indices[d].long() for d in range(out_indices.size(0))]
            # out_indices rows are (x, y[, z]); the grid is [..., z, y, x]
            return full[(slice(None), slice(None), *reversed(idx))]
        return full.reshape(full.size(0), full.size(1), -1)[:, :, out_indices.long()]

    def _render_plane(
        self,
        data_list: list[torch.Tensor],
        axis: str | None = None,
        index: int | None = None,
        mirror: Sequence[str] | None = None,
    ) -> np.ndarray:
        """Resample per-block cell data onto a uniform 2D plane, for rendering.

        The blocks are interpolated over the cell centers of all blocks at once,
        which is continuous across block interfaces and avoids the artifacts the
        PICT sampler introduces there. A 2D domain is resampled as a whole; of a
        3D domain a single plane is resampled, which costs no more than a 2D
        domain and avoids resampling the full volume.

        This detaches the data from the graph, so it is for rendering only. Use
        :meth:`_resample_blocks` for anything that feeds observations or needs to
        stay differentiable.

        Parameters
        ----------
        data_list: list[torch.Tensor]
            Per-block cell data, one entry per block of the domain.

        axis: str | None
            The axis to slice a 3D domain along, "x", "y" or "z". Must be None
            for a 2D domain. Defaults to None.

        index: int | None
            The index of the plane along ``axis`` of the render grid. If None,
            the middle of that axis is used. Defaults to None.

        mirror: Sequence[str] | None
            The axes ("x", "y", "z") to mirror the plane along. Axes that do not
            span the plane are ignored, so the same set of axes can be passed for
            every slice. If None, :attr:`_render_mirror_axes` is used. Defaults
            to None.

        Returns
        -------
        np.ndarray
            The plane of shape (H, W) for single-channel data, else (C, H, W).
        """
        data_list = [self._render_env_data(data) for data in data_list]
        if self._ndims == 2:
            if axis is not None:
                raise ValueError("A 2D domain has no slice axis")

            plane = self._resampler(data_list)
        elif axis is None:
            raise ValueError("Slicing a 3D domain needs an axis: 'x', 'y' or 'z'")
        else:
            plane = self._resampler.extract_slice(data_list, axis=axis, index=index)

        return self._mirror_plane(plane, axis=axis, mirror=mirror)

    def _render_env_data(self, data: torch.Tensor) -> torch.Tensor:
        """The data of the environment being rendered, see :meth:`render`.

        Per-environment block data ``[E, C, ...]`` is reduced to ``[1, C, ...]``;
        anything else (shared data, or data already of one environment) is
        returned as is.
        """
        if torch.is_tensor(data) and data.dim() == self._ndims + 2 and data.size(0) > 1:
            return data[self._render_env_idx : self._render_env_idx + 1]
        return data

    def _mirror_plane(
        self,
        plane: np.ndarray,
        axis: str | None,
        mirror: Sequence[str] | None,
    ) -> np.ndarray:
        """Mirror a rendered plane along the requested axes.

        See :meth:`_render_plane`.
        """
        mirror_axes = self._render_mirror_axes if mirror is None else tuple(mirror)
        if not mirror_axes:
            return plane

        invalid = set(mirror_axes) - {"x", "y", "z"}
        if invalid:
            raise ValueError(
                f"Invalid mirror axes {sorted(invalid)}, expected 'x', 'y' or 'z'"
            )

        # The plane is (vertical, horizontal), possibly with a leading channel
        # axis, so its axes are the last two either way
        plane_axes = slice_plane_axes(axis)
        flip_axes = tuple(
            plane_axes.index(name) - 2 for name in mirror_axes if name in plane_axes
        )
        if not flip_axes:
            return plane

        return np.flip(plane, axis=flip_axes)

    def _vorticity_blocks(self) -> list[torch.Tensor]:
        """Return the per-block vorticity, before any resampling.

        Returns
        -------
        list[torch.Tensor]
            One entry per block, of shape [E, 1, Y, X] in 2D or [E, 3, Z, Y, X]
            in 3D, with E the number of environments.
        """
        self._domain.UpdateDomainData()
        gradients = _C.ComputeSpatialVelocityGradients(self._domain)

        # gradients[block][k] is the gradient of the k'th velocity component,
        # with the channel axis holding the spatial direction: grad_u[:, i] = du/dx_i
        vorticity_blocks = []
        for block_id in range(len(gradients)):
            if self._ndims == 2:
                grad_u, grad_v = gradients[block_id]

                du_dy = grad_u[:, 1, :, :]
                dv_dx = grad_v[:, 0, :, :]

                vorticity_block = (dv_dx - du_dy).unsqueeze(1)
            else:
                grad_u, grad_v, grad_w = gradients[block_id]

                du_dy = grad_u[:, 1, :, :]
                dv_dx = grad_v[:, 0, :, :]

                dw_dx = grad_w[:, 0, :, :]
                du_dz = grad_u[:, 2, :, :]

                dv_dz = grad_v[:, 2, :, :]
                dw_dy = grad_w[:, 1, :, :]

                vorticity_block = torch.stack(
                    [
                        dw_dy - dv_dz,
                        du_dz - dw_dx,
                        dv_dx - du_dy,
                    ],
                    dim=1,
                )

            vorticity_blocks += [vorticity_block]

        return vorticity_blocks

    def _squeeze_fields(self, fields: torch.Tensor) -> torch.Tensor:
        """Drop the singleton dims of resampled fields ``[E, C, ...]``.

        A single environment loses every singleton dim, as before batching
        existed; a vectorized environment keeps its env dim.
        """
        if not self._vectorized:
            return fields.squeeze()
        return fields.reshape(fields.size(0), *fields[0].squeeze().shape)

    def _vorticity_fields(self) -> torch.Tensor:
        """The resampled vorticity of every environment, ``[E, C, *spatial]``.

        The per-environment form the env implementations work with; environments
        that mask regions (e.g. a solid body) override this, and the public
        :meth:`get_vorticity` follows.
        """
        return self._resample_blocks(self._vorticity_blocks())

    def _velocity_fields(self) -> torch.Tensor:
        """The resampled velocity of every environment, ``[E, C, *spatial]``."""
        return self._resample_blocks(
            [block.velocity for block in self._domain.getBlocks()]
        )

    def _pressure_fields(self) -> torch.Tensor:
        """The resampled pressure of every environment, ``[E, 1, *spatial]``."""
        return self._resample_blocks(
            [block.pressure for block in self._domain.getBlocks()]
        )

    def _render_env_field(self, fields: torch.Tensor) -> torch.Tensor:
        """The field ``[C, *spatial]`` of the environment being rendered."""
        return fields[self._render_env_idx]

    def get_vorticity(
        self,
    ) -> torch.Tensor:
        """Get the vorticity field of the fluid.

        Returns
        -------
        torch.Tensor
            The vorticity field as a tensor, with a leading env dim for a
            vectorized environment.
        """
        return self._squeeze_fields(self._vorticity_fields())

    def get_velocity(
        self,
    ) -> torch.Tensor:
        """Get the velocity field of the fluid.

        Returns
        -------
        torch.Tensor
            The velocity field as a tensor, with a leading env dim for a
            vectorized environment.
        """
        return self._squeeze_fields(self._velocity_fields())

    def get_pressure(
        self,
    ) -> torch.Tensor:
        """Get the pressure field of the fluid.

        Returns
        -------
        torch.Tensor
            The pressure field as a tensor of shape (H, W) for 2D or (D, H, W) for
            3D, with a leading env dim for a vectorized environment.
        """
        return self._squeeze_fields(self._pressure_fields())

    @staticmethod
    def _format_render_data(
        data: np.ndarray,
        v_min: float | None = None,
        v_max: float | None = None,
        cmap: str = "viridis",
    ) -> np.ndarray:
        """Format data for rendering.
        This method normalizes the data and applies a colormap.

        Parameters
        ----------
        data: np.ndarray
            The data to be formatted.

        v_min: float | None
            The minimum value for normalization. If None, the minimum of the data is
            used.

        v_max: float | None
            The maximum value for normalization. If None, the maximum of the data is
            used.

        cmap: str
            The colormap to be applied.

        Returns
        -------
        np.ndarray
            The formatted data ready for rendering.
        """
        _v_min = np.min(data) if v_min is None else v_min
        _v_max = np.max(data) if v_max is None else v_max

        data = np.flip(data, axis=1)
        data = (data - _v_min) / (_v_max - _v_min)
        data = np.clip(data, 0.0, 1.0)
        return sns.color_palette(cmap, as_cmap=True)(data, bytes=True)[:, :, :3]

    def step(
        self, action: torch.Tensor
    ) -> tuple[
        dict[str, torch.Tensor],
        torch.Tensor,
        bool | torch.Tensor,
        bool | torch.Tensor,
        dict[str, torch.Tensor],
    ]:
        """Run one timestep of the environment's dynamics using the agent actions.

        When the end of an episode is reached (``terminated or truncated``), it is
        necessary to call :meth:`reset` to reset this environment's state for the next
        episode.

        Parameters
        ----------
        action: torch.Tensor
            The action to take, ``[n_envs, ...]`` for a vectorized environment.

        Returns
        -------
        tuple[
        dict[str, torch.Tensor], torch.Tensor, bool, bool, dict[str, torch.Tensor]]
            A tuple containing the observation, reward, terminated flag, truncated flag,
            and info dictionary. For a vectorized environment everything has a
            leading env dim, and the flags are bool tensors of shape ``[n_envs]``.
        """
        if not self._reset_called:
            raise RuntimeError(
                "Environment must be reset before stepping. Call 'reset()' before"
                "'step()'."
            )

        if not action.shape == self._zero_action.shape:
            raise ValueError(
                f"Action shape {action.shape} does not match expected shape "
                f"{self._zero_action.shape}."
            )

        # Policies usually act in float32; the boundary setters require the
        # domain dtype. The cast is differentiable, so the gradient reaches the
        # policy in its own dtype
        action = self._to_batched(action.to(dtype=self._dtype))

        step_fn = self._step_marl_impl if self._use_marl else self._step_impl
        if self._bptt_checkpoint and self._differentiable:
            if self._bptt_segment_size:
                obs, reward, terminated, info = self._segmented_step(action)
            else:
                obs, reward, terminated, info = self._checkpointed_step(action, step_fn)
        else:
            obs, reward, terminated, info = step_fn(action)

        self._n_steps += 1
        truncated = self._n_steps >= self._episode_length

        info = {k: v.detach() for k, v in info.items()}

        if self._vectorized:
            # All environments share the episode: they are truncated together, and
            # an environment cannot terminate on its own
            flags = torch.ones(self._n_envs, dtype=torch.bool, device=self._cuda_device)
            return (
                obs,
                reward,
                flags & bool(terminated),
                flags & truncated,
                info,
            )
        return (
            self._from_batched(obs),
            self._from_batched(reward),
            terminated,
            truncated,
            self._from_batched(info),
        )

    def _step_impl(
        self, action: torch.Tensor
    ) -> tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]:
        """One environment step: advance the simulation, then close the step off.

        The step is split at the seam checkpointing needs it split at, so an env
        only implements the two halves: :meth:`_advance_impl` and
        :meth:`_finish_step`. Every env is cuttable into sub-step checkpoint
        segments by construction. Whether it is actually cut is
        ``bptt_segment_size``, which each env defaults for itself.

        Parameters
        ----------
        action: torch.Tensor
            The action to take.

        Returns
        -------
        tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]
            A tuple containing the observation, reward, terminated flag, and info
            dictionary.
        """
        return self._finish_step(self._advance_impl(action, self._n_sim_steps))

    @abstractmethod
    def _advance_impl(
        self, action: torch.Tensor, n_sim_steps: int
    ) -> dict[str, torch.Tensor]:
        """Advance the simulation by ``n_sim_steps`` PISO steps.

        Parameters
        ----------
        action: torch.Tensor
            The action to take.
        n_sim_steps: int
            Number of PISO steps to run, which is a segment of an env step rather
            than necessarily the whole of one.

        Returns
        -------
        dict[str, torch.Tensor]
            Per-substep metrics, each with ``n_sim_steps`` entries along dim 0.
        """
        raise NotImplementedError

    @abstractmethod
    def _finish_step(
        self, metrics: dict[str, torch.Tensor]
    ) -> tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]:
        """Close one env step off the per-substep metrics of all of its segments.

        Runs once per env step, outside any checkpoint segment, on the state the
        last segment left in the domain, which is still connected to the graph,
        so an observation taken here is differentiable.

        Parameters
        ----------
        metrics: dict[str, torch.Tensor]
            Per-substep metrics of the whole env step, as returned by
            :meth:`_advance_impl` and concatenated over its segments.

        Returns
        -------
        tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]
            A tuple containing the observation, reward, terminated flag, and info
            dictionary.
        """
        raise NotImplementedError

    def _step_marl_impl(
        self, action: torch.Tensor
    ) -> tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]:
        """One multi-agent environment step, split like the single-agent one.

        The agents act on the simulation through the action they are handed, so the
        advancing half is the same :meth:`_advance_impl`. Only the closing half
        differs, in that it hands back per-agent observations and rewards. An env
        therefore implements :meth:`_finish_marl_step` and gets the same sub-step
        checkpoint segments the single-agent step has.

        Parameters
        ----------
        action: torch.Tensor
            The individual agent actions.

        Returns
        -------
        tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]
            A tuple containing the local observations, local rewards, a global
            terminated flag, and a global info dictionary.
        """
        return self._finish_marl_step(self._advance_impl(action, self._n_sim_steps))

    def _finish_marl_step(
        self, metrics: dict[str, torch.Tensor]
    ) -> tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]:
        """Close one env step off per agent, the multi-agent :meth:`_finish_step`.

        Runs under the same conditions as :meth:`_finish_step`: once per env step,
        outside any checkpoint segment, on the state the last segment left. It is
        implemented by every env that sets ``_supports_marl``.

        Parameters
        ----------
        metrics: dict[str, torch.Tensor]
            Per-substep metrics of the whole env step, as returned by
            :meth:`_advance_impl` and concatenated over its segments.

        Returns
        -------
        tuple[dict[str, torch.Tensor], torch.Tensor, bool, dict[str, torch.Tensor]]
            A tuple containing the local observations, local rewards, a global
            terminated flag, and a global info dictionary.
        """
        raise NotImplementedError

    @property
    def _n_sim_steps(self) -> int:
        """The number of simulation steps per environment step."""
        return max(1, int(self._step_length / self._dt))

    def seed(self, seed: int) -> None:
        """Update the random seeds and seed the random number generators.

        Parameters
        ----------
        seed: int
            The seed to set. If None, the current seed is used.
        """
        if seed is None:
            raise ValueError("Seed cannot be None.")

        self._seed = seed
        self._torch_rng_cuda = torch.Generator(device=self._cuda_device).manual_seed(
            seed
        )
        self._torch_rng_cpu = torch.Generator(device=self._cpu_device).manual_seed(seed)
        self._np_rng = np.random.default_rng(seed)

    def reset(
        self,
        seed: int | None = None,
        randomize: bool | None = None,
        domain_idx: int | Sequence[int] | None = None,
    ) -> tuple[dict[str, torch.Tensor], dict[str, torch.Tensor]]:
        """Resets the environment to an initial internal state, returning an initial
        observation and info.

        Parameters
        ----------
        seed: int | None
            The seed to use for random number generation. If None, the current seed is
            used.

        randomize: bool | None
            Whether to randomize the initial state. If None, the default behavior is
            used.

        domain_idx: int | Sequence[int] | None
            Index of the initial domain to load, one for all environments or one per
            environment. Takes precedence over the random draw, so a randomized
            initial state can still start from a fixed domain. If None, every
            environment draws a random index when randomizing, and all start from
            the first initial domain otherwise. Defaults to None.

        Returns
        -------
        tuple[dict[str, torch.Tensor], dict[str, torch.Tensor]]
            A tuple containing the initial observation and an info dictionary.
            The observation has a leading env dim for a vectorized environment.
        """
        # First, we update the random seed as it may affect the initial state
        if seed is None:
            if self._seed is None:
                raise ValueError(
                    "Seed must be provided either during reset or by calling seed()."
                )
        else:
            self.seed(seed)

        # Then, we re-initialize the environment
        self._set_initial_state(randomize=randomize, domain_idx=domain_idx)

        # Drop the pressure warm-start guesses. They cannot change a converged
        # answer, but they change iteration counts and therefore round-off, so
        # carrying them across an episode boundary would make two episodes from
        # the same initial state depend on whatever ran before them
        self._sim.clear_pressure_guess()

        self._reset_called = True
        self._n_steps = 0
        self._n_episodes += 1

        self._apply_action(self._batched_zero_action)

        if self._use_marl:
            obs = self._get_local_obs()
        else:
            obs = self._get_global_obs()

        info: dict[str, torch.Tensor] = {}
        return self._from_batched(obs), info

    def render(
        self,
        save: bool = False,
        render_3d: bool = False,
        filename: str | None = None,
        output_path: Path | None = None,
        env_ids: int | Sequence[int] | None = None,
    ) -> np.ndarray:
        """Render the current state of the environment.

        Parameters
        ----------
        save: bool
            Whether to save the rendered frame as a PNG file. Defaults to False.

        render_3d: bool
            Whether to enable 3d rendering. Defaults to False.

        filename: str | None
            The filename of the saved PNG files. If None, a default name is used.
            Defaults to None.

        output_path: Path | None
            The output path to save the rendered files. If None, saves to the current
            directory. Defaults to None.

        env_ids: int | Sequence[int] | None
            The environments of a vectorized environment to render: one index for a
            single frame, a sequence for a stack of frames, None (the default) for
            all environments. Must be None for a single environment.

        Returns
        -------
        np.ndarray
            The rendered frame ``[H, W, 3]`` for a single environment (or a single
            ``env_ids`` index), else the frames ``[len(env_ids), H, W, 3]`` of the
            requested environments matching the layout of vectorized-env video
            recorders.
        """
        if env_ids is not None and not self._vectorized:
            raise ValueError("env_ids is only supported for a vectorized environment.")

        if not self._vectorized:
            ids, single = [0], True
        elif env_ids is None:
            ids, single = list(range(self._n_envs)), False
        elif isinstance(env_ids, (int, np.integer)):
            ids, single = [int(env_ids)], True
        else:
            ids, single = [int(i) for i in env_ids], False

        for env_idx in ids:
            if not 0 <= env_idx < self._n_envs:
                raise ValueError(
                    f"env_ids {env_idx} out of range for {self._n_envs} environments."
                )

        output_path = output_path or Path(".")
        output_path.mkdir(parents=True, exist_ok=True)

        frames = [
            self._render_env(env_idx, save, render_3d, filename, output_path)
            for env_idx in ids
        ]
        return frames[0] if single else np.stack(frames)

    def _render_env(
        self,
        env_idx: int,
        save: bool,
        render_3d: bool,
        filename: str | None,
        output_path: Path,
    ) -> np.ndarray:
        """Render one environment, see :meth:`render`."""
        from PIL import Image

        self._render_env_idx = env_idx
        try:
            render_data = self._get_render_data(
                render_3d=render_3d,
                output_path=output_path if save else None,
            )
        finally:
            self._render_env_idx = 0

        if save:
            # the frames of every environment of a vectorized env are kept apart
            suffix = (
                f"_env{env_idx + self._env_index_offset}" if self._vectorized else ""
            )
            for slice_name, data in render_data.items():
                img = Image.fromarray(data)
                if filename is not None:
                    img.save(output_path / f"{slice_name}{suffix}_{filename}.png")
                else:
                    img.save(
                        output_path
                        / f"{slice_name}{suffix}_{self._n_episodes}_{self._n_steps}.png"
                    )

        if self._default_render_key in render_data:
            return render_data[self._default_render_key]
        else:
            # Return the first slice's data as a numpy array
            return next(iter(render_data.values()))

