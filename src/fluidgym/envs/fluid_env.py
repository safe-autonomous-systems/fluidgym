    def _check_initial_domains_exists(
        self, mode: EnvMode | None = None, idx: int | None = None
    ) -> bool:
        """Check if the initial domain exists on disk.

        Parameters
        ----------
        mode: EnvMode | None
            Environment mode (e.g., 'train', 'val', 'test'). If None, checks for all
            tags. Defaults to None.

        idx: int | None
            Index of the initial domain to check. If None, checks for all indices.
              to None.

        Returns
        -------
        bool
            True if the initial domain exists, False otherwise.
        """
        modes = [EnvMode.TRAIN, EnvMode.VAL, EnvMode.TEST] if mode is None else [mode]
        idxs = range(N_INITIAL_DOMAINS) if idx is None else [idx]

        try:
            for _idx in idxs:
                for _mode in modes:
                    self._load_initial_domain(mode=_mode, idx=_idx)
            return True
        except FileNotFoundError:
            return False

    def _initial_domain_indices(
        self, randomize: bool, domain_idx: int | Sequence[int] | None
    ) -> list[int]:
        """The initial domain of every environment.

        ``domain_idx`` is one index for all environments or one per environment.
        Without it, every environment draws its own index when randomizing, and
        all start from the first initial domain otherwise. A single environment
        draws exactly as it did before batching existed.
        """
        if domain_idx is None:
            if randomize:
                return [
                    int(self._np_rng.integers(0, N_INITIAL_DOMAINS))
                    for _ in range(self._n_envs)
                ]
            return [0] * self._n_envs
        if isinstance(domain_idx, (int, np.integer)):
            return [int(domain_idx)] * self._n_envs
        idxs = [int(i) for i in domain_idx]
        if len(idxs) != self._n_envs:
            raise ValueError(
                f"Expected one domain index per environment ({self._n_envs}), got "
                f"{len(idxs)}."
            )
        return idxs

    def _batch_domain(self, domain: _C.Domain) -> _C.Domain:
        """Turn a single-environment domain into one of ``n_envs`` copies of it."""
        if self._n_envs > 1:
            domain.setBatchSize(self._n_envs)
            domain.PrepareSolve()
        return domain

    def _load_initial_domains(self, mode: EnvMode, idxs: list[int]) -> _C.Domain:
        """Load the initial domain of every environment into one batched domain.

        Every distinct index is read from disk once: the batched domain starts as
        ``n_envs`` copies of the first environment's domain, and the environments
        with another index get its state copied in.
        """
        from phipict.batching import copy_env_state

        domain = self._batch_domain(self._load_initial_domain(mode=mode, idx=idxs[0]))
        for idx in dict.fromkeys(idxs):
            if idx == idxs[0]:
                continue
            src = self._load_initial_domain(mode=mode, idx=idx)
            for env_idx, env_domain_idx in enumerate(idxs):
                if env_domain_idx == idx:
                    copy_env_state(domain, env_idx, src)
        return domain

    def _set_initial_state(
        self,
        randomize: bool | None = None,
        domain_idx: int | Sequence[int] | None = None,
    ) -> None:
        """Set the initial state of the environment.

        Parameters
        ----------
        randomize: bool | None
            Whether to randomize the initial state. If None, the default behavior is
            used.

        domain_idx: int | Sequence[int] | None
            Index of the initial domain to load, one for all environments or one per
            environment. Takes precedence over the random draw, so a randomized
            initial state can still start from a fixed domain. If None, a random
            index is used when randomizing and the first initial domain otherwise.
            Defaults to None.
        """
        self._sim = None  # type: ignore
        self._domain = None  # type: ignore
        gc.collect()
        torch.cuda.empty_cache()

        if randomize is None:
            randomize = self._randomize_initial_state

        if self.__load_domain_on_reset:
            idxs = self._initial_domain_indices(randomize, domain_idx)
            try:
                self._domain = self._load_initial_domains(mode=self.mode, idxs=idxs)
            except FileNotFoundError as err:
                raise RuntimeError(
                    "Initial domain not found. Please ensure it was downloaded."
                ) from err
            episodes: list[pd.DataFrame | None] = []
            for idx in idxs:
                try:
                    episodes.append(
                        self._load_uncontrolled_episode(idx=idx, mode=self.mode)
                    )
                except FileNotFoundError:
                    self._logger.warning(
                        "Uncontrolled episode data not found for domain %d in mode %s.",
                        idx,
                        self.mode.value,
                    )
                    episodes.append(None)
            self._uncontrolled_episodes = episodes
        else:
            self._domain = self._batch_domain(self._get_domain())
            self._uncontrolled_episodes = [None] * self._n_envs

        hooks = self._get_hooks(self._domain)
        self._sim = self._build_simulation(self._domain, hooks)

        # Some envs may need additional initialization
        self._additional_initialization()

        if randomize:
            with torch.no_grad():
                self._randomize_domain()

